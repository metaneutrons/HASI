import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { copyFileSync, mkdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourceRoot = join(packageRoot, 'src');
const templatePath = join(sourceRoot, 'app-view-template.html');
const generatedHtmlPath = join(sourceRoot, 'app-view.generated.html');
const generatedMetadataPath = join(sourceRoot, 'app-view-metadata.generated.ts');
const expectedSdkVersion = '2.0.3';
const bundlePlaceholder = '/*__HASI_APP_SDK_BUNDLE__*/';
const licensePlaceholder = '<!--__HASI_APP_SDK_LICENSE__*/';

const sdkEntry = import.meta.resolve('@hasi/plugin-sdk');
const sdkRequire = createRequire(sdkEntry);
const sdkBundlePath = realpathSync(sdkRequire.resolve('@modelcontextprotocol/ext-apps/app-with-deps'));
const sdkPackage = findExtAppsPackage(sdkBundlePath);
if (sdkPackage.metadata.version !== expectedSdkVersion) {
  throw new Error(`MCP Apps browser bundle version ${sdkPackage.metadata.version} does not match pinned ${expectedSdkVersion}`);
}

const sdkSource = readFileSync(sdkBundlePath, 'utf8');
const sdkLicense = readFileSync(join(sdkPackage.root, 'LICENSE'), 'utf8').trim();
const exportStart = sdkSource.lastIndexOf('export{');
const exportTable = exportStart < 0 ? '' : /^export\{([\s\S]*)\};?\s*$/.exec(sdkSource.slice(exportStart).trim())?.[1] ?? '';
const appConstructor = /(?:^|,)([\w$]+) as App(?:,|$)/.exec(exportTable)?.[1];
const transportConstructor = /(?:^|,)([\w$]+) as PostMessageTransport(?:,|$)/.exec(exportTable)?.[1];
if (!appConstructor || !transportConstructor) {
  throw new Error('The pinned MCP Apps SDK bundle is missing App or PostMessageTransport');
}

const browserBundle = `${sdkSource.slice(0, exportStart)}\nglobalThis.__HASI_APPS_SDK__ = { App: ${appConstructor}, PostMessageTransport: ${transportConstructor} };`
  .replace(/<\/script/gi, '<\\/script');
const template = readFileSync(templatePath, 'utf8');
if (template.split(bundlePlaceholder).length !== 2 || template.split(licensePlaceholder).length !== 2) {
  throw new Error('The Anny app HTML template must contain exactly one SDK bundle and license placeholder');
}
const licenseNotice = `<!-- Bundled browser SDK: @modelcontextprotocol/ext-apps ${expectedSdkVersion}; package metadata declares MIT. Full upstream LICENSE text follows.\n${sdkLicense}\n-->`;
const html = template
  .replace(bundlePlaceholder, () => browserBundle)
  .replace(licensePlaceholder, () => licenseNotice);
const byteLength = Buffer.byteLength(html, 'utf8');
if (byteLength === 0 || byteLength > 1_024 * 1_024) {
  throw new Error(`Generated Anny app HTML is outside the allowed size (${byteLength} bytes)`);
}

const resourceSha256 = createHash('sha256').update(html, 'utf8').digest('hex');
const sdkSha256 = createHash('sha256').update(sdkSource, 'utf8').digest('hex');

if (process.argv.includes('--copy-dist')) {
  const distRoot = join(packageRoot, 'dist');
  mkdirSync(distRoot, { recursive: true });
  copyFileSync(generatedHtmlPath, join(distRoot, 'app-view.generated.html'));
  process.exit(0);
}

writeFileSync(generatedHtmlPath, html);
writeFileSync(
  generatedMetadataPath,
  `/** Generated by scripts/build-app-view.mjs from the pinned MCP Apps ${expectedSdkVersion} browser distribution. */\n` +
    `export const annyAppViewSdkVersion = ${JSON.stringify(expectedSdkVersion)};\n` +
    `export const annyAppViewSdkSha256 = ${JSON.stringify(sdkSha256)};\n` +
    `export const annyAppViewSha256 = ${JSON.stringify(resourceSha256)};\n`,
);

console.log(`Generated pinned Anny app resource (${byteLength} bytes, sha256 ${resourceSha256}).`);

function findExtAppsPackage(entryPath) {
  let current = dirname(entryPath);
  for (;;) {
    const candidatePath = join(current, 'package.json');
    try {
      const candidate = JSON.parse(readFileSync(candidatePath, 'utf8'));
      if (candidate.name === '@modelcontextprotocol/ext-apps') return { root: current, metadata: candidate };
    } catch {
      // Continue to the nearest package root; the target bundle path is trusted build input.
    }
    const parent = dirname(current);
    if (parent === current) break;
    current = parent;
  }
  throw new Error('Could not locate the MCP Apps package metadata for the pinned browser bundle');
}
